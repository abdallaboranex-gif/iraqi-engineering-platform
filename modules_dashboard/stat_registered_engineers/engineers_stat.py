import streamlit as st

def render_engineers_stat():
    """
    برنامج مستقل لعرض العداد الإجمالي للمهندسين والمكاتب العراقية المسجلة.
    """
    st.metric(
        label="👷 المهندسون والمكاتب المسجلة",
        value="18,532",
        delta="🔒 قاعدة بيانات وطنية موثقة",
        delta_color="off"
    )
    if st.button("عرض التوزيع الجغرافي 🗺️", key="btn_stat_eng"):
        st.info("هنت: جاري تجهيز لوحة التوزيع الرقمي للمحافظات العراقية بالتعاون مع النقابة.")
