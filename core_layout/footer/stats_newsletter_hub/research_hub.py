import streamlit as st

def render_research_hub():
    """
    برنامج مستقل لإدارة النشرة الهندسية الموحدة بالتعاون مع نقابة المهندسين والجامعات العراقية.
    """
    st.markdown("### 🏛️ مركز البحوث والتعليمات الوطنية الموحد")
    st.write("نافذة معرفية رسمية لنشر البحوث الأكاديمية وتعاميم وزارة التخطيط ونقابة المهندسين العراقيين.")
    
    # تبويب داخلي مصغر معزول لتنظيم المصادر
    tab_univ, tab_synd = st.tabs(["🎓 بحوث الجامعات العراقية", "📜 تعاميم وتعليمات النقابة"])
    
    with tab_univ:
        st.markdown("<b>📚 أحدث المستخلصات البحثية المرفوعة:</b>", unsafe_allow_html=True)
        st.markdown("""
        * 🧪 *الجامعة التكنولوجية (قسم البناء والإنشاءات):* بحث حول كفاءة الثرمستون المحلي في العزل الحراري لمباني وسط العراق (2026).
        * 🧪 *جامعة بغداد (كلية الهندسة):* دراسة هبوط الأسس في التربة الطينية الرسوبية لمحافظة ذي قار ومطابقتها للكود العراقي.
        """)
        
    with tab_synd:
        st.markdown("<b>📢 بلاغات وتعديلات الكودات الرسمية:</b>", unsafe_allow_html=True)
        st.info("⚠️ تعميم نقابة المهندسين: إلزام كافة المكاتب الاستشارية بتطبيق الملحق الجليدي رقم 4 الخاص بـ 'كود الرياح العراقي المحدث' في تصاميم الهياكل الحديدية ابتداءً من العام الحالي.")

    # صندوق الاشتراك البريدي الذكي
    st.markdown("<b>📧 النشرة البريدية الهندسية الذكية</b>", unsafe_allow_html=True)
    email_input = st.text_input("أدخل بريدك الإلكتروني ليصلك ملخص البحوث والتعليمات فور صدورها:", key="txt_newsletter_email")
    if st.button("اشترك الآن 🔔", key="btn_newsletter_sub"):
        if email_input:
            st.success("🎉 تم تسجيل بريدك بنجاح! تم ربط حسابك بمرصد تحديثات الكود العراقي.")
        else:
            st.warning("الرجاء كتابة البريد الإلكتروني أولاً.")
